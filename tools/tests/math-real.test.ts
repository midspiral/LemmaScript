import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Project, ScriptTarget } from "ts-morph";
import { extractModule } from "../src/extract.ts";
import { resolveModule } from "../src/resolve.ts";
import { narrowModule } from "../src/narrow.ts";
import { transformModuleDafny, transformModuleLean } from "../src/transform.ts";
import { emitDafnyFile } from "../src/dafny-emit.ts";
import { emitLeanFile, resetLeanModule } from "../src/lean-emit.ts";

const fixture = readFileSync(new URL("../fixtures/math-real.ts", import.meta.url), "utf8");

function sourceModule(text: string) {
  const project = new Project({ compilerOptions: {
    strict: true, target: ScriptTarget.ESNext, lib: ["lib.esnext.d.ts"], types: [], skipLibCheck: true,
  } });
  const source = project.createSourceFile("math.ts", text);
  assert.deepEqual(project.getPreEmitDiagnostics(), [], "regressions must be valid TypeScript");
  return narrowModule(resolveModule(extractModule(source)));
}

function emitSource(text: string): string {
  const { typesFile, defFile } = transformModuleDafny(sourceModule(text));
  return emitDafnyFile({ ...defFile, decls: [...(typesFile?.decls ?? []), ...defFile.decls] }, "math.ts");
}

test("integer Math output stays byte-identical", () => {
  const output = emitSource(`
export function magnitude(n: number): number { return Math.abs(n); }
export function smaller(a: number, b: number): number { return Math.min(a, b); }
export function larger(a: number, b: number): number { return Math.max(a, b); }
export function clampUnit(n: number): number { return Math.min(1, Math.max(0, n)); }
export function natural(n: number): number {
  //@ type n nat
  //@ type \\result nat
  return Math.abs(n);
}
`);
  assert.equal(output, `// Generated by lsc from math.ts

function MathAbs(x: int): nat { if x >= 0 then x else -x }

function MathMin(a: int, b: int): int { if a <= b then a else b }

function MathMax(a: int, b: int): int { if a >= b then a else b }

function magnitude(n: int): int
{
  MathAbs(n)
}

function smaller(a: int, b: int): int
{
  MathMin(a, b)
}

function larger(a: int, b: int): int
{
  MathMax(a, b)
}

function clampUnit(n: int): int
{
  MathMin(1, MathMax(0, n))
}

function natural(n: nat): nat
{
  MathAbs(n)
}
`);
});

test("real Math helpers preserve real operands and lift mixed integer operands", () => {
  const output = emitSource(fixture);
  for (const call of [
    "MathAbsReal(t)",
    "MathMinReal(a, b)",
    "MathMaxReal(a, b)",
    "MathMinReal((1 as real), MathMaxReal((0 as real), t))",
    "MathMinReal((n as real), t)",
    "MathMinReal(t, (n as real))",
    "MathMaxReal(t, (n as real))",
    "MathMaxReal((n as real), t)",
    "MathMaxReal((|values| as real), t)",
    "MathMinReal(MathAbsReal(-0.5), MathMaxReal(0.25, 0.75))",
  ]) assert.ok(output.includes(call), `missing ${call}\n${output}`);
  for (const helper of ["MathAbsReal", "MathMinReal", "MathMaxReal"]) {
    assert.equal(output.match(new RegExp(`function ${helper}\\(`, "g"))?.length, 1);
  }
  assert.doesNotMatch(output, /\bMath(?:Abs|Min|Max)\(/);
});

test("Dafny verifies real Math contracts without proof additions", () => {
  const output = emitSource(fixture);
  const dir = mkdtempSync(join(tmpdir(), "lsc-math-real-"));
  try {
    const proof = join(dir, "math.dfy");
    writeFileSync(proof, output);
    const result = spawnSync("dafny", ["verify", "--verification-time-limit", "10", proof],
      { encoding: "utf8", timeout: 60_000 });
    assert.ifError(result.error);
    assert.equal(result.status, 0, result.stdout + result.stderr);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("Lean still rejects real Math arithmetic", () => {
  assert.throws(() => {
    const { typesFile, defFile } = transformModuleLean(sourceModule(fixture));
    resetLeanModule();
    emitLeanFile({ ...defFile, decls: [...(typesFile?.decls ?? []), ...defFile.decls] });
  }, /real arithmetic is not supported by the Lean backend/);
});
