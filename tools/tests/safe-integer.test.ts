import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Project, ScriptTarget } from "ts-morph";
import { extractModule } from "../src/extract";
import { resolveModule } from "../src/resolve";
import { narrowModule } from "../src/narrow";
import { transformModuleDafny, transformModuleLean } from "../src/transform";
import { emitDafnyFile } from "../src/dafny-emit";
import { emitLeanFile, resetLeanModule } from "../src/lean-emit";

const source = `
export function isSafe(n: number): boolean {
  return Number.isSafeInteger(n);
}
export function isSafeBig(b: bigint): boolean {
  return Number.isSafeInteger(b);
}
`;

function sourceModule(text = source) {
  const project = new Project({ compilerOptions: { strict: true,
    target: ScriptTarget.ESNext, lib: ["lib.esnext.d.ts"], types: [], skipLibCheck: true } });
  const file = project.createSourceFile("safe.ts", text);
  assert.deepEqual(project.getPreEmitDiagnostics(), [], "the regression must be valid TypeScript");
  return narrowModule(resolveModule(extractModule(file)));
}

function dafnySource(text = source): string {
  const { typesFile, defFile } = transformModuleDafny(sourceModule(text));
  return emitDafnyFile({ ...defFile, decls: [...(typesFile?.decls ?? []), ...defFile.decls] }, "safe.ts");
}

function leanSource(text = source): string {
  const { typesFile, defFile } = transformModuleLean(sourceModule(text));
  resetLeanModule();
  return emitLeanFile({ ...defFile, decls: [...(typesFile?.decls ?? []), ...defFile.decls] });
}

function verify(text: string) {
  const dir = mkdtempSync(join(tmpdir(), "lsc-safe-integer-"));
  try {
    const proof = join(dir, "safe.dfy");
    writeFileSync(proof, text);
    const result = spawnSync("dafny", ["verify", "--verification-time-limit", "20", proof],
      { encoding: "utf8", timeout: 120_000 });
    assert.ifError(result.error);
    return { status: result.status, output: result.stdout + result.stderr };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// JavaScript: Number.isSafeInteger(2 ** 53 - 1) === true, (2 ** 53) === false,
// and symmetrically for the negatives. LemmaScript models `number` as an
// unbounded integer, so the bound must appear explicitly in the lowering.
// A bigint is not a number, so Number.isSafeInteger(5n) === false.
const facts = `
lemma SafeIntegerBounds()
  ensures isSafe(9007199254740991) && isSafe(-9007199254740991) && isSafe(0)
  ensures !isSafe(9007199254740992) && !isSafe(-9007199254740992)
  ensures !isSafeBig(0) && !isSafeBig(5)
{}
`;

test("Dafny lowers Number.isSafeInteger to the 2^53 - 1 bound", () => {
  const output = dafnySource();
  assert.equal(output, `// Generated by lsc from safe.ts

function isSafe(n: int): bool
{
  ((-9007199254740991 <= n) && (n <= 9007199254740991))
}

function isSafeBig(b: int): bool
{
  false
}
`);
  const ok = verify(output + facts);
  assert.equal(ok.status, 0, ok.output);
  for (const claim of ["isSafe(9007199254740992)", "isSafeBig(5)"]) {
    const wrong = verify(output + `\nlemma Wrong() ensures ${claim} {}\n`);
    assert.notEqual(wrong.status, 0, wrong.output);
    assert.match(wrong.output, /could not be proved|might not hold/);
  }
});

test("Lean lowers Number.isSafeInteger to the 2^53 - 1 bound", () => {
  const output = leanSource();
  assert.doesNotMatch(output, /isSafeInteger|IsSafeIntegerReal/, output);
  assert.match(output, /-9007199254740991 ≤ n ∧ n ≤ 9007199254740991/, output);
  assert.match(output, /def isSafeBig[^\n]*\n(?:[^\n]*\n)*?\s*false\b/, output);
});

const realSource = `
export function isSafeReal(x: number): boolean {
  //@ type x real
  return Number.isSafeInteger(x);
}
export function isSafeQuotient(a: number, b: number): boolean {
  //@ requires b !== 0
  return Number.isSafeInteger(a / b);
}
export function fractionalLiteral(): boolean { return Number.isSafeInteger(1.5); }
export function negativeFraction(): boolean { return Number.isSafeInteger(-0.5); }
export function fractionalQuotient(): boolean { return Number.isSafeInteger(3 / 2); }
export function integralQuotient(): boolean { return Number.isSafeInteger(4 / 2); }
export function fractionalSum(): boolean { return Number.isSafeInteger(0.5 + 0.5); }
`;

test("Dafny verifies real integrality, signed bounds and quotient checks", () => {
  const output = dafnySource(realSource);
  assert.equal(output.match(/predicate IsSafeIntegerReal\(/g)?.length, 1);
  const ok = verify(output + `
lemma SafeRealCases()
  ensures isSafeReal(0.0) && isSafeReal(-2.0) && isSafeReal(2.0)
  ensures isSafeReal(9007199254740991.0) && isSafeReal(-9007199254740991.0)
  ensures !isSafeReal(9007199254740992.0) && !isSafeReal(-9007199254740992.0)
  ensures !isSafeReal(0.5) && !isSafeReal(-0.5)
  ensures !fractionalLiteral() && !negativeFraction() && !fractionalQuotient()
  ensures integralQuotient() && fractionalSum()
  ensures !isSafeQuotient(3, 2) && isSafeQuotient(4, 2)
  ensures !isSafeQuotient(-3, 2) && isSafeQuotient(-4, 2)
{}
`);
  assert.equal(ok.status, 0, ok.output);
  for (const claim of ["isSafeReal(1.5)", "isSafeReal(9007199254740992.0)", "!integralQuotient()"]) {
    const wrong = verify(output + `\nlemma Wrong() ensures ${claim} {}\n`);
    assert.notEqual(wrong.status, 0, wrong.output);
    assert.match(wrong.output, /could not be proved|might not hold/);
  }
});

test("Dafny evaluates a real method argument once", () => {
  const output = dafnySource(`
function increment(x: number): number {
  //@ type x real
  //@ type \\result real
  //@ ensures \\result == x + 0.5
  let value = x;
  value += 0.5;
  return value;
}
export function safeAfterIncrement(x: number): boolean {
  //@ type x real
  return Number.isSafeInteger(increment(x));
}
`);
  assert.equal(output.match(/:= increment\(/g)?.length, 1, output);
  const ok = verify(output);
  assert.equal(ok.status, 0, ok.output);
});

test("Dafny preserves a real argument's division and callee preconditions", () => {
  for (const [text, diagnostic] of [
    [
      `export function uncheckedQuotient(a: number, b: number): boolean {
        return Number.isSafeInteger(a / b);
      }`,
      /division by zero/,
    ],
    [
      `function positiveHalf(x: number): number {
        //@ requires x > 0
        //@ type \\result real
        return x / 2;
      }
      export function uncheckedCall(x: number): boolean {
        return Number.isSafeInteger(positiveHalf(x));
      }`,
      /precondition.*could not be proved|precondition.*might not hold/,
    ],
  ] as const) {
    const wrong = verify(dafnySource(text));
    assert.notEqual(wrong.status, 0, wrong.output);
    assert.match(wrong.output, diagnostic);
  }
});

for (const argument of ["1.5", "-0.5", "0.5 + 0.5", "3 / 2"]) {
  test(`Lean rejects Number.isSafeInteger(${argument}) during generation`, () => {
    assert.throws(() => leanSource(`
      export function check(): boolean { return Number.isSafeInteger(${argument}); }
    `), /real arithmetic is not supported by the Lean backend/);
  });
}

test("Lean rejects isSafeInteger on real parameters and variable quotients", () => {
  for (const text of [realSource, `
    export function check(a: number, b: number): boolean {
      //@ requires b !== 0
      return Number.isSafeInteger(a / b);
    }
  `]) assert.throws(() => leanSource(text), /real arithmetic is not supported by the Lean backend/);
});

for (const [backend, emit] of [["Dafny", dafnySource], ["Lean", leanSource]] as const) {
  test(`${backend} reports unsupported isSafeInteger argument types explicitly`, () => {
    for (const [type, resolved] of [
      ["string", "string"], ["boolean", "bool"], ["number[]", "array"],
      ["number | undefined", "optional"], ["unknown", "unknown"],
    ]) {
      assert.throws(() => emit(`
        export function check(x: ${type}): boolean { return Number.isSafeInteger(x); }
      `), new RegExp(`Unsupported Number\\.isSafeInteger argument type: ${resolved};`));
    }
  });

  test(`${backend} reports unsupported isSafeInteger arities explicitly`, () => {
    for (const args of ["", "1, 2"]) {
      assert.throws(() => emit(`
        export function check(): boolean {
          // @ts-expect-error Exercise JavaScript calls outside the TypeScript signature.
          return Number.isSafeInteger(${args});
        }
      `), /Number\.isSafeInteger expects exactly one argument/);
    }
  });
}
