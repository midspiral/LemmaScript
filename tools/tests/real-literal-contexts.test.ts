test("real return and argument positions contextually type literal branches", () => {
  const mod = sourceModule(fixture);
  const direction = mod.functions.find(f => f.name === "direction")!.body[0];
  assert.ok(direction.kind === "return" && direction.value.kind === "conditional");
  assert.equal(direction.value.ty.kind, "real");
  assert.equal(direction.value.then.ty.kind, "real");
  assert.equal(direction.value.else.ty.kind, "real");
  const halfOfOne = mod.functions.find(f => f.name === "halfOfOne")!.body[0];
  assert.ok(halfOfOne.kind === "return" && halfOfOne.value.kind === "call");
  assert.equal(halfOfOne.value.args[0].ty.kind, "real");
  const maybeZero = mod.functions.find(f => f.name === "maybeZero")!.body[0];
  assert.ok(maybeZero.kind === "return" && maybeZero.value.kind === "conditional");
  assert.deepEqual(maybeZero.value.ty, { kind: "optional", inner: { kind: "real" } });
  assert.equal(maybeZero.value.then.ty.kind, "real");
  assert.equal(maybeZero.value.else.ty.kind, "void");
});

test("Dafny casts contextual real literals, including folded negatives and optional payloads", () => {
  const output = emitSource(fixture);
  for (const expected of [
    "    (0 as real)\n  else\n    t",
    "    (-1 as real)\n  else\n    (1 as real)",
    "half((1 as real))",
    "  (-2 as real)",
    "var value := (0 as real);",
    "value := (-1 as real);",
    "Some((0 as real))",
    "Some((-1 as real))",
    "withDefault(Some((-1 as real)))",
    "[(0 as real), (-1 as real)]",
  ]) assert.ok(output.includes(expected), `missing ${expected}\n${output}`);
  assert.doesNotMatch(output, /Some\(Some\(/);
});

test("Dafny verifies real literal contexts without proof additions", () => {
  const dir = mkdtempSync(join(tmpdir(), "lsc-real-literal-contexts-"));
  try {
    const proof = join(dir, "literals.dfy");
    writeFileSync(proof, emitSource(fixture));
    const result = spawnSync("dafny", ["verify", "--verification-time-limit", "10", proof],
      { encoding: "utf8", timeout: 60_000 });
    assert.ifError(result.error);
    assert.equal(result.status, 0, result.stdout + result.stderr);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("Lean still rejects contextually real literals", () => {
  assert.throws(() => {
    const { typesFile, defFile } = transformModuleLean(narrowModule(sourceModule(fixture)));
    resetLeanModule();
    emitLeanFile({ ...defFile, decls: [...(typesFile?.decls ?? []), ...defFile.decls] });
  }, /real arithmetic is not supported by the Lean backend/);
});
